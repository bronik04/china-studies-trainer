import { createHash } from 'node:crypto';
import { COUNTRY_FRAME_OUTSET } from '../src/map/target-size';

/**
 * Настройки генератора геометрии стран. Живут здесь, а не в самом генераторе:
 * их обязан видеть и валидатор, а импортировать генератор ему нельзя — тот при
 * загрузке сразу читает выжимку и переписывает файл.
 */
export const COUNTRY_GEOMETRY_TUNING = {
  /** Допуск упрощения. Тот же, что у форм рельефа: карта одна и та же. */
  simplifyTolerance: 0.4,
  /**
   * Меньше этой площади — обрезок, а не земля: кромка кадра режет контуры, и от
   * дальних островов остаются треугольники в доли единицы. Рисовать их значит
   * ставить на карту крапинки, в которые нельзя попасть и которые ничего не
   * говорят.
   */
  minRingArea: 1,
  /**
   * Знаков после запятой в путях. Единица карты — около пикселя на опорной
   * ширине, а упрощение уже сдвинуло вершины на 0.4 единицы: второй знак
   * прибавляет 4.5 КБ gzip к куску слоя и не показывает ничего. Приблизить
   * карту в этих играх нельзя — увеличение им не передаётся.
   */
  pathPrecision: 1,
} as const;

/**
 * Русские имена спорных участков там, где имя набора не годится. Natural Earth
 * зовёт северо-западные долины просто «Бутан» — тем же словом, что саму страну,
 * которая в обеих играх бывает ответом, и читалка экрана сообщала бы, что
 * искомая страна и есть спорная территория. Имя участка берётся у нашего же
 * источника (`docs/sources/countries.md`), формулировка спора — по-прежнему у
 * набора.
 */
export const DISPUTED_NAMES_RU: Readonly<Record<string, string>> = {
  'bhutan-northwest-valleys': 'Северо-западные долины Бутана',
};

/**
 * Отпечаток входов генератора геометрии стран — затем же, зачем
 * `reliefInputsFingerprint`: забытый генератор не должен проходить сборку.
 *
 * Хеша одной выжимки мало. Контуры обрезаются по кадру и упрощаются, поэтому в
 * отпечаток входят и множитель кадра, и допуски: иначе `COUNTRY_FRAME_OUTSET`
 * можно поднять, не перегенерировав, — сборка останется зелёной, а у стран
 * появятся рубленые края посреди видимой области, ради устранения которых
 * обрезка по расширенному кадру и делается.
 */
export function countryInputsFingerprint(sourceJson: string): string {
  return createHash('sha256')
    .update(
      [
        `outset=${COUNTRY_FRAME_OUTSET}`,
        `simplify=${COUNTRY_GEOMETRY_TUNING.simplifyTolerance}`,
        `minArea=${COUNTRY_GEOMETRY_TUNING.minRingArea}`,
        `precision=${COUNTRY_GEOMETRY_TUNING.pathPrecision}`,
        `names=${JSON.stringify(DISPUTED_NAMES_RU)}`,
        sourceJson,
      ].join('\n'),
    )
    .digest('hex')
    .slice(0, 16);
}
