/**
 * Регионы, которые невозможно выбрать указателем: Макао занимает 0.7×1.4
 * единицы viewBox, Гонконг — 7.1×5.0. Они выносятся маркерами в свободное
 * море юго-восточнее Гуандуна, а их собственные контуры становятся
 * декоративными. Маркер несёт `role`, `tabindex` и имя, поэтому выбирается и
 * указателем, и с клавиатуры; контур при этом остаётся на своём настоящем
 * месте и прежней формы.
 *
 * Почему у мелких регионов два разных приёма. Выноска уводит знак в пустую
 * воду, и это возможно только там, где вода рядом: у Макао и Гонконга она
 * есть. У Пекина, Тяньцзиня, Шанхая и Тайваня пустого места вокруг нет, и
 * увести знак некуда — им остаётся невидимая цель, заходящая на территорию
 * крупного соседа (`generate-hit-targets.ts`). Свести оба приёма к одному не
 * выйдет: разными их делает не устройство карты, а география.
 *
 * Координаты якорей — центры габаритов контуров в единицах viewBox,
 * измеренные по самой карте. Координаты маркеров выбраны вручную в пустой
 * акватории; выносные линии не пересекаются.
 */
export type CalloutTarget = {
  readonly regionId: string;
  readonly regionKind: string;
  readonly label: string;
  readonly shortLabel: string;
  readonly anchor: readonly [number, number];
  readonly marker: readonly [number, number];
};

