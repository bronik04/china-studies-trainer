import { isOnLand, LAND_RINGS } from './land';

/*
 * Контуров в разметке ровно 34 — по числу областей. Колец больше: у приморских
 * регионов есть острова. Проверка держит и то, что в список не попало ничего
 * лишнего: выноски Макао и Гонконга и цели нажатия мелких областей записаны в
 * SVG кругами и линиями, а не контурами.
 */
it('разбирает все области карты', () => {
  expect(LAND_RINGS.length).toBeGreaterThanOrEqual(34);
});

/* Точка на Лёссовом плато: заведомо суша и заведомо не у границы. */
it('считает сушей точку в середине страны', () => {
  expect(isOnLand(455, 320)).toBe(true);
});

/* Жёлтое море восточнее Шаньдуна. */
it('не считает сушей море', () => {
  expect(isOnLand(650, 320)).toBe(false);
});

/*
 * Индия южнее Гималаев. Точка лежит внутри контура Тибетского нагорья — форма
 * выходит за границу страны, — но не на суше Китая. Маска прячет там ступени,
 * а нажатия не отсекает: без этой проверки нагорье выбиралось бы за границей.
 */
it('не считает сушей землю за границей', () => {
  expect(isOnLand(120, 430)).toBe(false);
});
