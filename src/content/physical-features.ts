import type { Fact, PhysicalFeature, PhysicalKind, ReliefStep } from './types';

/**
 * Двенадцать целей физической географии: шесть рек и шесть форм рельефа.
 * Состав утверждён владельцем продукта 2026-08-05.
 *
 * Реки взяты не по одной длине, а по типам бассейнов: тихоокеанский сток,
 * северная граница с Россией, трансграничная река и бессточный запад. Формы —
 * по одной-две на каждую ступень рельефа.
 *
 * Координат здесь нет и не будет: справочник не зависит от файла карты.
 * Геометрия живёт в `src/map/physical-geometry.ts`, её пишет генератор.
 *
 * `regionIds` перечисляет только те регионы, по которым объект проходит явно.
 * Пограничные случаи — Янцзы вдоль межи Хубэя и Хунани, Наньпаньцзян по меже
 * Юньнани и Гуйчжоу — не заявляются: `validate:map` требует, чтобы каждый
 * заявленный регион был действительно задет, а генерализованная линия у самой
 * межи может лечь по любую её сторону.
 */

/**
 * Род объекта назван словом — по той же причине, что и род региона: на
 * физической карте род передан цветом полосы высоты и формой знака, а цвет не
 * может быть единственным каналом (DESIGN_SYSTEM.md).
 *
 * Живёт в справочнике, а не в атласе: тот же род называет и надзаголовок
 * коллекции об объекте.
 */
export const PHYSICAL_KIND_LABELS: Readonly<Record<PhysicalKind, string>> = {
  river: 'Река',
  landform: 'Форма рельефа',
  lake: 'Озеро',
};

/**
 * Слово рода в карточке. Одного `kind` мало: хребет — тоже `landform` и
 * получил бы «Форма рельефа», хотя ученик ищет глазами именно хребет.
 */
export function physicalKindLabel(feature: PhysicalFeature): string {
  if (feature.kind === 'landform' && feature.landform === 'range') {
    return 'Горный хребет';
  }

  return PHYSICAL_KIND_LABELS[feature.kind];
}

/** Объект по идентификатору. Справочник маленький, поиск линейный. */
export function physicalFeatureById(
  id: string,
): PhysicalFeature | undefined {
  return physicalFeatures.find((feature) => feature.id === id);
}

const RIVERS = ['natural-earth-rivers-5.1.2'] as const;
const LANDFORMS = ['natural-earth-geography-regions-5.1.2'] as const;
const LAKES = ['natural-earth-lakes-5.1.2'] as const;

function river(
  id: string,
  nameRu: string,
  nameZh: string,
  pinyin: string,
  riverNums: readonly number[],
  regionIds: readonly string[],
): PhysicalFeature {
  return {
    id,
    kind: 'river',
    nameRu,
    nameZh,
    pinyin,
    riverNums,
    regionIds,
    facts: FACTS[id] ?? [],
    sourceIds: RIVERS,
  };
}

function landform(
  id: string,
  nameRu: string,
  nameZh: string,
  pinyin: string,
  step: ReliefStep,
  shape: 'plateau' | 'plain' | 'basin' | 'desert' | 'range',
  regionIds: readonly string[],
): PhysicalFeature {
  return {
    id,
    kind: 'landform',
    nameRu,
    nameZh,
    pinyin,
    step,
    landform: shape,
    regionIds,
    facts: FACTS[id] ?? [],
    sourceIds: LANDFORMS,
  };
}

function lake(
  id: string,
  nameRu: string,
  nameZh: string,
  pinyin: string,
  lakeIds: readonly number[],
  regionIds: readonly string[],
): PhysicalFeature {
  return {
    id,
    kind: 'lake',
    nameRu,
    nameZh,
    pinyin,
    lakeIds,
    regionIds,
    facts: FACTS[id] ?? [],
    sourceIds: LAKES,
  };
}

